#!/usr/bin/env node
/**
 * Every `route('…')` a controller or view calls must exist, and every
 * `view('…')` / `@include` / `@extends` target must be a real template.
 *
 * A renamed route or a deleted partial fails at render time with
 * `RouteNotFoundException` / `InvalidArgumentException` — a 500 on a page nobody
 * had opened since the rename. This harness resolves both directions statically:
 * the route names come from routes_integrity_check.js (so controller-scoped
 * groups, `Route::resource`, fluent registrations and loop-generated names are
 * all included), and the template names from the views directory.
 *
 * Request-parameter lookups such as `$request->route('token')` are not URL
 * generation and are ignored.
 *
 * Requires php-parser (indirectly, through routes_integrity_check.js); without
 * it the check reports SKIP and exits 0.
 *
 * Usage: node deploy/dev/audit/route_reference_check.js [project-root]
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = process.argv[2] || path.resolve(__dirname, '../../..');

// Route names, generated by the route audit itself so both always agree.
const nameFile = path.join(os.tmpdir(), `pms-route-names-${process.pid}.txt`);
try {
  execFileSync(process.execPath, [path.join(__dirname, 'routes_integrity_check.js'), ROOT], {
    env: {...process.env, DUMP_NAMES: nameFile},
    stdio: 'pipe',
  });
} catch (err) {
  console.log('route reference check: SKIP (route audit could not run — ' + String(err.message).split('\n')[0] + ')');
  process.exit(0);
}
if (!fs.existsSync(nameFile)) {
  console.log('route reference check: SKIP (no route name list produced)');
  process.exit(0);
}
const routeNames = new Set(fs.readFileSync(nameFile, 'utf8').split('\n').filter(Boolean));
fs.unlinkSync(nameFile);

const walk = dir =>
  fs.readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
    const p = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(p) : [p];
  });

const sources = [
  ...walk(path.join(ROOT, 'app')).filter(f => f.endsWith('.php')),
  ...walk(path.join(ROOT, 'routes')).filter(f => f.endsWith('.php')),
  ...walk(path.join(ROOT, 'resources/views')).filter(f => f.endsWith('.blade.php')),
];

const failures = [];
let routeRefs = 0;
let viewRefs = 0;

// route('name') / route("name") — but not $request->route('name').
const ROUTE_REF = /(?<![\w>$:])(?<!->)route\(\s*['"]([^'"]+)['"]/g;

const viewRoot = path.join(ROOT, 'resources/views');
const viewNames = new Set(
  walk(viewRoot)
    .filter(f => f.endsWith('.blade.php'))
    .map(f => path.relative(viewRoot, f).replace(/\.blade\.php$/, '').split(path.sep).join('.'))
);
const VIEW_REF = /(?:@include(?:If|When)?|@extends|@component|view)\s*\(\s*['"]([^'"]+)['"]/g;

for (const file of sources) {
  const rel = path.relative(ROOT, file);
  const src = fs.readFileSync(file, 'utf8');

  for (const m of src.matchAll(ROUTE_REF)) {
    routeRefs++;
    if (!routeNames.has(m[1])) {
      const line = src.slice(0, m.index).split('\n').length;
      failures.push(`${rel}:${line}  route('${m[1]}') is not registered`);
    }
  }

  for (const m of src.matchAll(VIEW_REF)) {
    viewRefs++;
    if (!viewNames.has(m[1])) {
      const line = src.slice(0, m.index).split('\n').length;
      failures.push(`${rel}:${line}  view '${m[1]}' does not exist`);
    }
  }
}

console.log(`route names: ${routeNames.size} | route() references: ${routeRefs} | view references: ${viewRefs}`);
console.log(`unresolved references: ${failures.length}`);
failures.slice(0, 40).forEach(f => console.log('  - ' + f));
process.exit(failures.length ? 1 : 0);
