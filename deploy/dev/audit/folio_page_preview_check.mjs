import fs from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';
const html = fs.readFileSync('deploy/dev/previews/folio-page.html', 'utf8');
const errors = [];
const vc = new VirtualConsole(); vc.on('jsdomError', error => errors.push(error.message));
const dom = new JSDOM(html, { runScripts: 'dangerously', url: 'http://example.test/', virtualConsole: vc });
const { document, Event } = dom.window;
const text = selector => document.querySelector(selector)?.textContent.replace(/\s+/g, ' ').trim() ?? '';
assert.match(document.title, /^Folio FOL-00124/);
assert.match(text('[role="note"]'), /Sample folio preview.*forms cannot save.*not yet available/i);
assert.match(text('.stats'), /2,541\.00.*500\.00.*2,041\.00/);
assert.match(text('.grid.g-3-1 > div:nth-child(2)'), /Ama Mensah.*Room202.*RES-00124/);
assert.equal(document.querySelectorAll('.card.flush table tbody tr').length, 4);
assert.match(text('.card.flush'), /Room tariff.*Advance received.*Restaurant/);
assert.match(text('.actions'), /Open.*Post Charge.*Payment.*Check-out/);
assert.doesNotMatch(text('.actions'), /\[object Object\]/);
assert.equal(document.querySelector('#payModal').classList.contains('show'), false);
document.querySelector('[data-modal="payModal"]').click();
assert.equal(document.querySelector('#payModal').classList.contains('show'), true);
document.querySelector('#folioToggleSplit').click();
assert.equal(document.querySelector('#folioSplitPayment').hidden, false);
document.querySelector('#payModal [data-close]').click();
assert.equal(document.querySelector('#payModal').classList.contains('show'), false);
const submit = new Event('submit', { bubbles: true, cancelable: true });
document.querySelector('#payModal form').dispatchEvent(submit);
assert.equal(submit.defaultPrevented, true);
assert.deepEqual(errors, []);
console.log('14 full folio sample preview assertions passed.');
