import fs from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';
const errors = [];
const vc = new VirtualConsole(); vc.on('jsdomError', e => errors.push(e.message));
const dom = new JSDOM(fs.readFileSync('deploy/dev/previews/laundry-request.html', 'utf8'), { url: 'https://preview.test/', runScripts: 'dangerously', virtualConsole: vc });
const { document: doc, Event } = dom.window;
doc.dispatchEvent(new Event('DOMContentLoaded'));
assert.match(doc.title, /^Collect Laundry/);
assert.match(doc.querySelector('[role=note]').textContent, /fictional.*cannot be saved/i);
assert.equal(doc.querySelector('[name=type]').value, 'guest');
assert.equal(doc.querySelectorAll('[name=type][value=walk_in]').length, 0);
assert.equal(doc.querySelector('#lfStay').value, '71');
assert.equal(doc.querySelectorAll('#lfStay option[value="72"]').length, 0);
assert.equal(doc.querySelector('[name=guest_request_id]').value, '61');
assert.equal(doc.querySelectorAll('[name=speed]:checked').length, 1);
assert.equal(doc.querySelector('[name=speed]:checked').value, 'express');
assert.ok([...doc.querySelectorAll('.alert-info')].some(el => /GR-00234.*202/s.test(el.textContent)));
assert.ok([...doc.querySelectorAll('.lf-walk')].every(el => el.style.display === 'none'));
const qty = doc.querySelector('[name="q[1][wash]"]');
qty.value = '2'; qty.dispatchEvent(new Event('input', { bubbles: true }));
assert.equal(doc.querySelector('#lgPcs').textContent, '2');
assert.match(doc.querySelector('#lgExp').textContent, /express/);
const submit = new Event('submit', { bubbles: true, cancelable: true });
doc.querySelector('#laundryForm').dispatchEvent(submit);
assert.equal(submit.defaultPrevented, true);
assert.deepEqual(errors, []);
dom.window.close();
console.log('Laundry request preview assertions passed.');
