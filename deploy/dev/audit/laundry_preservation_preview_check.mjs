import fs from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM, VirtualConsole } from 'jsdom';
const errors = [];
const vc = new VirtualConsole(); vc.on('jsdomError', e => errors.push(e.message));
const html = fs.readFileSync('deploy/dev/previews/laundry-preservation.html', 'utf8');
const dom = new JSDOM(html, { url: 'https://preview.test/', runScripts: 'dangerously', virtualConsole: vc });
const { document: doc, Event } = dom.window;
doc.dispatchEvent(new Event('DOMContentLoaded'));
assert.match(doc.title, /^Laundry LND-000412/);
assert.match(doc.querySelector('[role=note]').textContent, /fictional.*cannot be saved/i);
assert.match(doc.querySelector('#itemsCard').textContent, /previously itemised services keep their recorded unit price/i);
assert.match(doc.querySelector('#itemsCard').textContent, /Recorded as Shirt/);
const shirt = doc.querySelector('[name="q[1][wash]"]');
assert.equal(shirt.value, '2'); assert.equal(shirt.dataset.rate, '60');
assert.match(doc.querySelector('.laundry-preserved').textContent, /Evening jacket.*Loose button at collection/s);
assert.equal(doc.querySelector('#lgPcs').textContent, '7');
assert.equal(doc.querySelector('#lgSub').textContent, '790.00');
const removal = doc.querySelector('[data-preserved-line]');
removal.checked = true; removal.dispatchEvent(new Event('change', { bubbles: true }));
assert.equal(doc.querySelector('#lgPcs').textContent, '6');
assert.equal(doc.querySelector('#lgSub').textContent, '690.00');
removal.checked = false; removal.dispatchEvent(new Event('change', { bubbles: true }));
assert.equal(doc.querySelector('#lgPcs').textContent, '7');
shirt.value = '3'; shirt.dispatchEvent(new Event('input', { bubbles: true }));
assert.equal(doc.querySelector('#lgPcs').textContent, '8');
assert.equal(doc.querySelector('#lgSub').textContent, '850.00');
const submit = new Event('submit', { bubbles: true, cancelable: true });
doc.querySelector('#itemsCard').dispatchEvent(submit);
assert.equal(submit.defaultPrevented, true);
assert.deepEqual(errors, []);
dom.window.close();
console.log('Laundry preservation preview assertions passed.');
