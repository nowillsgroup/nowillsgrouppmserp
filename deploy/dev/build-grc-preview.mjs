#!/usr/bin/env node
/**
 * Build the Guest Registration Card as the printed sheet the desk hands to a guest.
 *
 * Nothing on the sheet is hand-copied. resources/views/frontdesk/grc.blade.php is
 * rendered by deploy/dev/preview/blade-render.mjs against deploy/dev/preview/grc-sample.mjs,
 * and the frame around it — the stationery head, the print bar, the page canvas — is the
 * one resources/views/layouts/print.blade.php draws, reproduced here because that layout
 * is a Blade @extends target rather than a view this renderer can wrap.
 *
 * Output: deploy/dev/previews/guest-registration-card.html
 *
 * Run: node deploy/dev/build-grc-preview.mjs [--check]
 *      --check exits 1 when the file on disk is stale instead of rewriting it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BladePreview } from './preview/blade-render.mjs';
import { grcContext, HOTEL } from './preview/grc-sample.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = path.join(ROOT, 'deploy/dev/previews/guest-registration-card.html');
const checkOnly = process.argv.includes('--check');

const esc = (value) => String(value ?? '')
  .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const newLog = () => ({
  expressions: 0, fallbacks: 0,
  failed: [], conditionsDefaulted: [], phpSkipped: [],
  unknownComponents: [], unknownDirectives: [], errors: [],
});

/** The stationery: resources/views/layouts/print.blade.php, section by section. */
function printPage({ title, docTitle, docMeta, head, content, pageClass = '', hotel = HOTEL }) {
  return `<!doctype html>
<!-- Generated by deploy/dev/build-grc-preview.mjs from resources/views/frontdesk/grc.blade.php
     inside the stationery of resources/views/layouts/print.blade.php, with the sample in
     deploy/dev/preview/grc-sample.mjs. Do not edit this file — rebuild it. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)} · ${esc(hotel.name)}</title>
<link rel="stylesheet" href="/css/app.css">
<style>body{background:#eef1f6}.print-head>div{min-width:0}.print-head .small{overflow-wrap:anywhere}</style>
${head}</head>
<body>
<div class="print-bar no-print">
  <a class="btn" href="/previews">← Back</a>
  <button class="btn btn-primary" onclick="window.print()">Print</button>
</div>
<div class="print-page ${pageClass}">
  <div class="print-head">
    <div>${hotel.logo_path ? `<img src="${esc(hotel.logo_path)}" alt="" style="max-height:54px;margin-bottom:.3rem;display:block">` : ''}<h2>${esc(hotel.name)}</h2>
      <div class="small text-2">${esc(hotel.address)}${hotel.city ? `, ${esc(hotel.city)}` : ''}${hotel.state ? `, ${esc(hotel.state)}` : ''} ${esc(hotel.pincode)}</div>
      <div class="small text-2">Ph: ${esc(hotel.phone)} · ${esc(hotel.email)}</div>
      ${hotel.website ? `<div class="small text-2">Website: ${esc(hotel.website)}</div>` : ''}
      ${hotel.tax_number ? `<div class="small"><b>TIN:</b> ${esc(hotel.tax_number)}</div>` : ''}
    </div>
    <div class="right"><h2 style="color:#166534">${esc(docTitle)}</h2>${docMeta}</div>
  </div>
  ${content}
</div>
</body></html>
`;
}

/** Renders the card for one sample state and returns the whole sheet. */
export function renderCard(options = {}) {
  const ctx = grcContext(options);
  const log = newLog();
  const renderer = new BladePreview({ root: ROOT, ctx, log });

  const content = renderer.section('frontdesk/grc', 'content', ctx.scope);
  const docMeta = renderer.section('frontdesk/grc', 'docmeta', ctx.scope);
  const head = renderer.push('frontdesk/grc', 'head', ctx.scope);

  return {
    html: printPage({
      title: `GRC ${ctx.stay.reservation.reservation_no}`,
      docTitle: 'Guest Registration Card',
      docMeta,
      head,
      content,
      pageClass: 'grc-sheet',
    }),
    log,
    ctx,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { html, log } = renderCard();
  const stale = !fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== html;

  if (checkOnly) {
    if (stale) {
      console.error('guest-registration-card.html is out of date — run node deploy/dev/build-grc-preview.mjs');
      process.exit(1);
    }
    console.log('guest-registration-card.html is up to date');
  } else if (stale) {
    fs.writeFileSync(OUT, html);
    console.log(`wrote deploy/dev/previews/guest-registration-card.html (${html.length} bytes)`);
  } else {
    console.log('guest-registration-card.html is up to date');
  }

  if (log.failed.length) {
    console.log(`  unresolved expressions .. ${log.failed.length}`);
    for (const item of log.failed.slice(0, 12)) console.log(`    ${item.expr.slice(0, 110)} → ${item.reason}`);
  }
  if (log.unknownDirectives.length) {
    console.log(`  unknown directives ...... ${[...new Set(log.unknownDirectives)].join(', ')}`);
  }
  console.log(`menu sections: 0 | expressions: ${log.expressions}`);
}
