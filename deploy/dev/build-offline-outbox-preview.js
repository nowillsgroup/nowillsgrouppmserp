#!/usr/bin/env node
/*
 * Builds deploy/dev/previews/offline-outbox.html from the real screen.
 *
 * The Blade view is rendered and the real /js/offline-queue.js draws it from a
 * sample outbox: two changes still waiting to be sent, a front-desk check-in the
 * server refused because the room was taken, and a folio charge that clashed. The
 * result is frozen as a static page for the preview server, so the preview cannot
 * drift from the screen.
 *
 * Run: node deploy/dev/build-offline-outbox-preview.js [--check]
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const OUT = resolve(ROOT, 'deploy/dev/previews/offline-outbox.html');
const read = path => readFileSync(resolve(ROOT, path), 'utf8');

let JSDOM;
try {
  ({ JSDOM } = await import('jsdom'));
} catch (_) {
  console.log('offline outbox preview: SKIP (jsdom is not installed — npm install --no-save jsdom)');
  process.exit(0);
}

function screen() {
  const blade = read('resources/views/offline/queue.blade.php');
  const start = blade.indexOf("@section('content')");
  const end = blade.indexOf('@endsection', start);
  let html = blade.slice(start + "@section('content')".length, end);
  html = html.replace(/\{\{--[\s\S]*?--\}\}/g, '');
  html = html.replace(/<x-icon[^>]*\/>/g, '');
  html = html.replace(/\{\{[^}]*\}\}/g, '');
  return `<!doctype html><html><head><meta charset="utf-8"></head><body>${html}</body></html>`;
}

const MINUTE = 60 * 1000;
const started = Date.parse('2026-11-05T19:38:00+00:00');

const ROWS = [
  {
    id: 'op-7b41c2e8-1', operation: 'pos.order.kot', status: 'retry', attempts: 2,
    label: 'Sent dishes to the kitchen · T1 · 2 dishes', created_at: started - 9 * MINUTE,
    error: 'The server could not apply this change yet.', payload: { order_id: 214, lines: [{ menu_item_id: 102, qty: 1 }, { menu_item_id: 101, qty: 1, variants: [501] }] },
  },
  {
    id: 'op-7b41c2e8-2', operation: 'frontdesk.charge', status: 'queued', attempts: 0,
    label: 'Charge GH₵ 45.00 · Room 204 · Yaw Antwi', created_at: started - 6 * MINUTE,
    error: null, payload: { stay_id: 31, category: 'minibar', description: 'Minibar — 2 bottles of water', amount: 45, apply_tax: true, business_date: '2026-11-05' },
  },
  {
    id: 'op-7b41c2e8-3', operation: 'frontdesk.checkin', status: 'rejected', attempts: 1,
    label: 'Check in Kwabena Osei → room 103', created_at: started - 14 * MINUTE,
    error: 'Room 103 was taken by the time this check-in reached the server.', payload: { stay_id: 42, room_id: 3, business_date: '2026-11-05' },
  },
  {
    id: 'op-7b41c2e8-4', operation: 'guest_request.create', status: 'conflict', attempts: 1,
    label: 'Logged a guest request · Room 212 · towels', created_at: started - 21 * MINUTE,
    error: 'Changed on the server while this device was offline.', payload: { stay_id: 32, category: 'housekeeping', item: 'Extra towels', quantity: 2 },
  },
];

const dom = new JSDOM(screen(), { url: 'https://pms.test/offline/queue', runScripts: 'outside-only' });
const { window } = dom;
const { document } = window;

Object.defineProperty(window.navigator, 'onLine', { configurable: true, get: () => false });

window.PmsOffline = {
  pending: async () => ROWS.map(row => ({ ...row })),
  retry: async id => ROWS.find(row => row.id === id) || null,
  discard: async id => ROWS.find(row => row.id === id) || null,
  flush: async () => ({ sent: 0, applied: [], conflicts: [] }),
  status: () => ({ online: false, syncing: false, queued: 2, conflicts: 1, rejected: 1, lastSync: started - 26 * MINUTE }),
  onChange: fn => { fn(window.PmsOffline.status()); return () => {}; },
  watch: () => {},
};

const settle = () => new Promise(done => setTimeout(done, 30));

window.eval(read('public/js/offline-queue.js'));
await settle();
// Open the first row's payload so the preview shows what a supervisor can inspect.
document.querySelector('[data-queue-problems] details').setAttribute('open', 'open');
await settle();

const body = document.getElementById('offlineQueue').outerHTML;

const page = `<!doctype html>
<!-- Generated by deploy/dev/build-offline-outbox-preview.js from resources/views/offline/queue.blade.php
     and the real public/js/offline-queue.js, driven with a sample outbox. The work shown is a fixed
     sample: the live screen reads this device's own IndexedDB queue. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Outbox · Nowills PMS</title>
<link rel="stylesheet" href="/css/app.css">
<link rel="stylesheet" href="/css/offline.css">
<link rel="stylesheet" href="/css/dashboard.css">
<style>body{background:#eef2ef;margin:0;padding:clamp(12px,2vw,24px)}.offline-queue{max-width:1200px;margin:0 auto}</style>
</head>
<body class="is-offline">
${body}
</body>
</html>
`;

if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== page) {
    console.error('offline outbox preview is stale — run node deploy/dev/build-offline-outbox-preview.js');
    process.exit(1);
  }
  console.log('offline outbox preview is current');
  process.exit(0);
}

writeFileSync(OUT, page);
console.log(`wrote deploy/dev/previews/offline-outbox.html (${Buffer.byteLength(page)} bytes)`);
